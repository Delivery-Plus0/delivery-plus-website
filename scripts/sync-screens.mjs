// Copies the real Delivery Plus screenshots and brand assets into the website and writes
// js/screens.js from the screenshot inventory, so the site stays a plain static folder
// (it also works when index.html is opened straight from disk).
//
// Usage (from website/): node scripts/sync-screens.mjs
//
// Source of truth: ../artifacts/delivery-plus-ui-screenshots (103 screenshots captured from the
// running apps on 2026-10-11, see its README) and the brand PNGs in the backend repository.
// Nothing is edited: files are copied byte for byte.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const workspace = resolve(site, '..');
const shotsRoot = join(workspace, 'artifacts', 'delivery-plus-ui-screenshots');
const inventory = JSON.parse(readFileSync(join(shotsRoot, 'inventory.json'), 'utf8'));

const copy = (from, to) => {
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
};

for (const shot of inventory.shots) {
  const from = join(shotsRoot, shot.file);
  if (!existsSync(from)) throw new Error(`Missing screenshot listed in the inventory: ${shot.file}`);
  copy(from, join(site, 'assets', 'screens', shot.file));
}

// The official brand assets (BRANDING.md): wordmark lockup and the badge mark. Not redrawn.
copy(join(workspace, 'delivery-plus', 'assets', 'logo.png'), join(site, 'assets', 'brand', 'logo.png'));
copy(join(workspace, 'delivery-plus', 'assets', 'icon.png'), join(site, 'assets', 'brand', 'icon.png'));

const screens = inventory.shots.map(({ file, app, screen, lang, dir, device, how, kind }) => ({
  file: `assets/screens/${file}`,
  app,
  screen,
  lang,
  dir,
  device,
  how,
  kind,
  group: file.split('/')[1], // en | ar | states | flow
}));

writeFileSync(
  join(site, 'js', 'screens.js'),
  `// Generated by scripts/sync-screens.mjs from artifacts/delivery-plus-ui-screenshots/inventory.json.\n` +
    `// Do not edit by hand. Captured ${inventory.capturedAt}.\n` +
    `window.DP_SCREENS = ${JSON.stringify(screens, null, 2)};\n`,
);

console.log(`Copied ${screens.length} screenshots and 2 brand files; wrote js/screens.js`);
